
import Foundation
import UIKit

extension UIColor {
    static func appColor() -> UIColor {
        return UIColor(named: "colorController")!
    }
    
    static func textColor() -> UIColor {
        return UIColor(named: "Title_Header")!
    }
    
    static func grayColor() -> UIColor {
        return UIColor(named: "homeColor")!
      }
}
